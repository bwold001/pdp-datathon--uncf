"""Write built tables to a database, SQLite or PostgreSQL, replacing what was there.

Only what differs between the two databases is here: column types, how to connect, the
parameter placeholder, and how a surrogate id keeps counting after a load. What the tables hold
comes from src/loader/tables.py, so both databases get the same rows.

Each table is created from config/destination_schema.yaml: its types, NOT NULL, primary key,
unique groups and foreign keys, including those over several columns (rules["foreign_keys"]). A single-column whole-number primary key, such as
course.course_id, also hands out the next id when a squad adds a row without one.

refresh() runs in one transaction: drop the model's tables, create them, insert every row, and
commit. Any failure rolls back, so the database keeps what it held before. A table outside the
model whose foreign key points at a model table stops the refresh before anything is dropped:
PostgreSQL refuses such a drop itself, and in SQLite dropping a table deletes its rows first,
which would fire that table's ON DELETE CASCADE or SET NULL.
"""

import sqlite3
from collections import defaultdict
from datetime import date, datetime, timezone
from pathlib import Path

from src.rules.rules import table_order

__all__ = ["BACKENDS", "table_order", "create_table_sql", "refresh"]


class _SQLite:
    name = "sqlite"
    placeholder = "?"
    types = {"str": "TEXT", "int": "INTEGER", "float": "REAL", "bool": "BOOLEAN", "date": "TEXT", "datetime": "TEXT"}
    surrogate = "INTEGER PRIMARY KEY"   # an alias of the rowid: a row added without an id gets the next one

    def connect(self, target):
        Path(target).parent.mkdir(parents=True, exist_ok=True)
        connection = sqlite3.connect(target, isolation_level=None)  # transactions are begun and ended below
        connection.execute("PRAGMA foreign_keys = ON")  # off by default in SQLite, and per connection
        return connection

    def begin(self, cursor):
        cursor.execute("BEGIN IMMEDIATE")

    def commit(self, connection):
        connection.execute("COMMIT")

    def rollback(self, connection):
        if connection.in_transaction:
            connection.execute("ROLLBACK")

    def referencing_tables(self, cursor, schema):
        """Tables outside the model with a foreign key to a model table, as 'table.column -> table'."""
        cursor.execute("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'")
        found = []
        for (table,) in cursor.fetchall():
            if table in schema:
                continue
            cursor.execute(f"PRAGMA foreign_key_list({_quote(table)})")
            found += [f"{table}.{key[3]} -> {key[2]}" for key in cursor.fetchall() if key[2] in schema]
        return found

    def value(self, value):
        """SQLite has no date type: dates and timestamps are stored as ISO 8601 text."""
        return value.isoformat() if isinstance(value, (date, datetime)) else value

    def after_insert(self, cursor, table, column):
        pass  # the rowid alias already continues from the largest id


class _Postgres:
    name = "postgres"
    placeholder = "%s"
    types = {"str": "TEXT", "int": "BIGINT", "float": "DOUBLE PRECISION", "bool": "BOOLEAN", "date": "DATE",
             "datetime": "TIMESTAMP"}
    surrogate = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"

    def connect(self, target):
        import psycopg  # only needed for this backend
        return psycopg.connect(target)  # not autocommit: the first statement begins the transaction

    def begin(self, cursor):
        pass

    def commit(self, connection):
        connection.commit()

    def rollback(self, connection):
        connection.rollback()

    def referencing_tables(self, cursor, schema):
        return []  # DROP TABLE without CASCADE fails and names them

    def value(self, value):
        return value

    def after_insert(self, cursor, table, column):
        """The loader writes ids itself, so move the identity on past the largest one."""
        cursor.execute(f"SELECT setval(pg_get_serial_sequence(%s, %s), "
                       f"COALESCE((SELECT MAX({_quote(column)}) FROM {_quote(table)}), 0) + 1, false)",
                       (_quote(table), column))


BACKENDS = {"sqlite": _SQLite(), "postgres": _Postgres()}


def create_table_sql(backend, schema, table, foreign_keys):
    fields = schema[table]
    pk = [c for c, f in fields.items() if f.get("primary_key")]
    surrogate = pk[0] if len(pk) == 1 and fields[pk[0]]["type"] == "int" else None
    lines = []
    for column, field in fields.items():
        if column == surrogate:
            lines.append(f"{_quote(column)} {backend.surrogate}")
        else:
            lines.append(f"{_quote(column)} {backend.types[field['type']]}" + ("" if field["nullable"] else " NOT NULL"))
    if pk and not surrogate:
        lines.append(f"PRIMARY KEY ({_columns(pk)})")
    groups = defaultdict(list)
    for column, field in fields.items():
        if field.get("unique"):
            groups[field["unique"]].append(column)
    lines += [f"UNIQUE ({_columns(columns)})" for columns in groups.values()]
    for columns, ref_table, ref_columns in foreign_keys.get(table, []):
        lines.append(f"FOREIGN KEY ({_columns(columns)}) REFERENCES {_quote(ref_table)} ({_columns(ref_columns)})")
    return f"CREATE TABLE {_quote(table)} (\n    " + ",\n    ".join(lines) + "\n)"


def refresh(backend, target, schema, foreign_keys, tables, batch_size, stamp=None):
    """Replace the model's tables in the database at target with tables, in one transaction.

    stamp, if given, is (table, column): just before the commit, that column of every row of that
    table is set to the time (UTC), in the database and in tables, so it says when the rows were
    written. Returns {table: rows inserted}. Raises whatever the database raises, after rolling back.
    """
    connection = backend.connect(target)
    inserted = {}
    try:
        cursor = connection.cursor()
        backend.begin(cursor)
        referencing = backend.referencing_tables(cursor, schema)
        if referencing:
            raise ValueError(f"tables outside the model point at it, so a full refresh would delete or change their "
                             f"rows: {', '.join(referencing)}. Drop or change those foreign keys, load, then add "
                             f"them again")
        order = table_order(schema, foreign_keys)
        for table in reversed(order):
            cursor.execute(f"DROP TABLE IF EXISTS {_quote(table)}")
        for table in order:
            cursor.execute(create_table_sql(backend, schema, table, foreign_keys))
        for table in order:
            columns = list(schema[table])
            sql = (f"INSERT INTO {_quote(table)} ({_columns(columns)}) "
                   f"VALUES ({', '.join([backend.placeholder] * len(columns))})")
            rows = tables.get(table, [])
            for start in range(0, len(rows), batch_size):
                cursor.executemany(sql, [[backend.value(row.get(c)) for c in columns]
                                         for row in rows[start:start + batch_size]])
            pk = [c for c, f in schema[table].items() if f.get("primary_key")]
            if len(pk) == 1 and schema[table][pk[0]]["type"] == "int":
                backend.after_insert(cursor, table, pk[0])
            inserted[table] = len(rows)
        if stamp:
            stamped, column = stamp
            now = _now()
            cursor.execute(f"UPDATE {_quote(stamped)} SET {_quote(column)} = {backend.placeholder}", [backend.value(now)])
            for row in tables.get(stamped, []):
                row[column] = now
        backend.commit(connection)
    except BaseException:
        backend.rollback(connection)
        raise
    finally:
        connection.close()
    return inserted


def _now():
    return datetime.now(timezone.utc).replace(tzinfo=None, microsecond=0)


def _quote(name):
    return '"' + name.replace('"', '""') + '"'


def _columns(columns):
    return ", ".join(_quote(c) for c in columns)
